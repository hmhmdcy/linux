#ifndef CAMSS_ICP_A5_IPE_H
#define CAMSS_ICP_A5_IPE_H

#include "camss-icp-a5-boot.h"
#include "camss-icp-a5-colour.h"

#define CAMSS_A5_IPE_FRAME_BYTES 3816U
#define CAMSS_A5_IPE_IQ_BYTES 2584U
#define CAMSS_A5_IPE_FRAME_ACK_BYTES 72U

struct camss_a5_ipe_buffer {
	u32 iova, bytes;
};

/* A wire builder, not a DMA mapping or submission interface. The future
 * request owner must map every range for both A5 and the relevant engines,
 * preserve buffers through completion/reset, and validate settings/commands.
 * Initial fixtures disable IQ modules; this builder does not inspect IQ
 * content. Command arrays remain empty. No hardware frame is submitted here.
 */
struct camss_a5_ipe_frame {
	struct camss_a5_ipe_buffer striping, iq, scratch, bl, input, output;
	const void *striping_cpu;
	u32 required_scratch_bytes, required_bl_bytes;
	u32 request_id, max_cores, target_time_ns;
	u64 user_data;
};

int camss_a5_ipe_striping_bytes(const void *data, u32 bytes, u32 *used);
int camss_a5_ipe_encode_frame(void *destination, u32 bytes,
			    const struct camss_a5_ipe_io *io,
			    const struct camss_a5_ipe_frame *frame);


/* Sleeping synchronous transfer with kernel-generated bypass IQ and striping.
 * Select either CPU pointers (legacy fixture) or two DMA-BUF references.
 * QBUF/DQBUF ownership is explicit; do not access or resubmit live images.
 * The core takes its own import references and retains all backing after
 * uncertain completion until A5 and both IPE engines are quiescent.
 */
struct camss_a5_ipe_job {
	const void *input;
	void *output;
	struct dma_buf *input_dma, *output_dma;
	u32 input_offset, output_offset;
	u32 input_bytes, output_bytes;
	u32 bl_bytes, request_id, max_cores, target_time_ns;
};
/* A negative errno alone cannot distinguish a local input rejection from
 * an uncertain firmware command. RESET_REQUIRED is the fail-closed default.
 * REJECTED proves no transfer MAP was attempted and all transient backing
 * was released; it never permits retiring unknown hardware DMA ownership.
 */
enum camss_a5_ipe_result {
	CAMSS_A5_IPE_RESET_REQUIRED,
	CAMSS_A5_IPE_REJECTED,
	CAMSS_A5_IPE_COMPLETE,
};
int camss_a5_ipe_run_status(struct camss_a5 *a5, struct camss_a5_session *session,
			  const struct camss_a5_ipe_job *job,
			  enum camss_a5_ipe_result *result);
/* Typed, synchronous colour extension; the legacy job layout is unchanged.
 * The core copies/validates cc before any firmware MAP. NULL retains bypass.
 * Colour/program storage uses the existing retained request parcel.
 */
int camss_a5_ipe_run_colour_status(struct camss_a5 *a5,
				 struct camss_a5_session *session,
				 const struct camss_a5_ipe_job *job,
				 const struct camss_a5_ipe_cc *cc,
				 enum camss_a5_ipe_result *result);
/* Optional typed pre/post conversion and CCM; NULL retains the old bypass.
 * Enabled modules are copied/validated before allocation or firmware MAP.
 */
int camss_a5_ipe_run_colour_chain_status(struct camss_a5 *a5,
				       struct camss_a5_session *session,
				       const struct camss_a5_ipe_job *job,
				       const struct camss_a5_ipe_colour *colour,
				       enum camss_a5_ipe_result *result);
int camss_a5_ipe_run(struct camss_a5 *a5, struct camss_a5_session *session,
		     const struct camss_a5_ipe_job *job);

int camss_a5_ipe_encode_bypass_iq(void *buffer, u32 bytes);


/* Inclusive ranges in descending output order for the disabled-IQ,
 * full-frame 1:1 NV12/NV21 path. No scaling or geometric warp is implied.
 */
struct camss_a5_ipe_partition {
	u16 fetch_first, fetch_last;
	u16 output_first, output_last;
};
int camss_a5_ipe_bypass_partitions(u32 width, u32 cores,
				 struct camss_a5_ipe_partition *output,
				 u32 capacity, u32 *count);

/* One full-frame unity-scale pass, matching NV12/NV21 input and output,
 * even width/height 128..8192; padded even strides/slices are accepted.
 * Both functions leave output parameters unchanged on failure.
 */
int camss_a5_ipe_bypass_size(const struct camss_a5_ipe_io *io, u32 cores,
			   u32 *bytes);
int camss_a5_ipe_encode_bypass_striping(void *buffer, u32 capacity,
				      const struct camss_a5_ipe_io *io,
				      u32 cores, u32 *used);

#endif
